#!/usr/bin/env bash
# ─── FortiAI Galaxy Store — Deploy on target server ───────────────────────────
# Run this on the Ubuntu server after copying the deploy/ folder there.
#
# Usage:  ./deploy.sh              # load images + start stack
#         ./deploy.sh --load-only  # just load images, don't start
#         ./deploy.sh --up-only    # just start (images already loaded)
#         ./deploy.sh --down       # tear down the stack
#         ./deploy.sh --status     # show running services
#         ./deploy.sh --logs       # tail all service logs
#
# Prerequisites: docker (20.10+), docker compose v2 plugin
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
IMAGE_DIR="$SCRIPT_DIR/images"

# ── Parse flags ───────────────────────────────────────────────────────────────
ACTION="full"
case "${1:-}" in
  --load-only) ACTION="load"   ;;
  --up-only)   ACTION="up"     ;;
  --down)      ACTION="down"   ;;
  --status)    ACTION="status" ;;
  --logs)      ACTION="logs"   ;;
esac

# ── Preflight checks ─────────────────────────────────────────────────────────
check_docker() {
  if ! command -v docker &>/dev/null; then
    echo "ERROR: docker not found. Install Docker first:"
    echo "  curl -fsSL https://get.docker.com | sh"
    exit 1
  fi
  if ! docker info &>/dev/null; then
    echo "ERROR: Docker daemon is not running."
    echo "  sudo systemctl start docker"
    exit 1
  fi
  if ! docker compose version &>/dev/null; then
    echo "ERROR: 'docker compose' (v2 plugin) not found."
    echo "  sudo apt-get update && sudo apt-get install -y docker-compose-plugin"
    exit 1
  fi
}

# ── .env bootstrap ────────────────────────────────────────────────────────────
ensure_env() {
  if [ ! -f "$SCRIPT_DIR/.env" ]; then
    echo ""
    echo "No .env found — creating one with generated secrets."

    # Generate APP_ENCRYPTION_KEY
    if python3 -c "from cryptography.fernet import Fernet" 2>/dev/null; then
      ENC_KEY=$(python3 -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())")
    else
      echo "WARNING: python3 cryptography not installed. Installing it now..."
      pip3 install cryptography 2>/dev/null || sudo pip3 install cryptography 2>/dev/null || true
      if python3 -c "from cryptography.fernet import Fernet" 2>/dev/null; then
        ENC_KEY=$(python3 -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())")
      else
        echo "ERROR: Cannot generate Fernet key. Install python3-cryptography:"
        echo "  sudo apt-get install -y python3-cryptography"
        echo "  OR: pip3 install cryptography"
        echo "Then re-run ./deploy.sh"
        exit 1
      fi
    fi

    SECRET=$(openssl rand -hex 32 2>/dev/null || python3 -c "import secrets; print(secrets.token_hex(32))")

    cat > "$SCRIPT_DIR/.env" <<ENVEOF
# ─── Generated by deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) ────────────────
APP_ENCRYPTION_KEY=${ENC_KEY}
SECRET_KEY=${SECRET}

ADMIN_EMAIL=admin@ftnt-apac-demo.local
ADMIN_PASSWORD=DemoPassword123!
ADMIN_NAME=Fortinet Admin

STORE_DATABASE_URL=sqlite+aiosqlite:////data/store.db
SHIPPING_DATABASE_URL=sqlite+aiosqlite:////data/shipping.db
API_PROXY_TARGET=http://api:8000

API_PORT=8000
FRONTEND_PORT=3000
MCP_STORE_PORT=8001
MCP_SHIPPING_PORT=8002
MCP_ROGUE_PORT=8003
MCP_POISON_PORT=8004
ENVEOF
    echo "  → $SCRIPT_DIR/.env created"
    echo "  → Review it (especially ADMIN_PASSWORD) before going live."
    echo ""
  fi
}

# ── Reassemble split chunks into .tar.gz, then load ──────────────────────────
load_images() {
  echo ""
  echo "═══════════════════════════════════════════════════════════════"
  echo "  Loading images from $IMAGE_DIR"
  echo "═══════════════════════════════════════════════════════════════"
  echo ""

  if [ ! -d "$IMAGE_DIR" ]; then
    echo "ERROR: $IMAGE_DIR not found."
    echo "       Did you copy the full deploy/ folder including images/?"
    exit 1
  fi

  # Detect host architecture: x86_64 → amd64, aarch64 → arm64
  HOST_ARCH=$(uname -m)
  case "$HOST_ARCH" in
    x86_64)  ARCH="amd64" ;;
    aarch64) ARCH="arm64" ;;
    arm64)   ARCH="arm64" ;;
    *)       echo "WARNING: Unknown arch $HOST_ARCH, trying amd64"; ARCH="amd64" ;;
  esac
  echo "  Host architecture: $HOST_ARCH → loading $ARCH images"
  echo ""

  # Discover services from chunk files (e.g. api-amd64.tar.gz.part-aa → api)
  SVCS=$(ls "$IMAGE_DIR"/*-${ARCH}.tar.gz.part-* 2>/dev/null \
    | sed "s|.*/||; s|-${ARCH}\.tar\.gz\.part-.*||" | sort -u)

  if [ -z "$SVCS" ]; then
    # Fallback: try already-assembled .tar.gz files
    SVCS=$(ls "$IMAGE_DIR"/*-${ARCH}.tar.gz 2>/dev/null \
      | sed "s|.*/||; s|-${ARCH}\.tar\.gz||" | sort -u)
  fi

  if [ -z "$SVCS" ]; then
    echo "ERROR: No $ARCH image chunks or tarballs found in $IMAGE_DIR"
    echo "       Available files:"
    ls "$IMAGE_DIR"/ 2>/dev/null || echo "       (empty)"
    exit 1
  fi

  for SVC in $SVCS; do
    TARBALL="${IMAGE_DIR}/${SVC}-${ARCH}.tar.gz"

    # Reassemble chunks if they exist
    if ls "${IMAGE_DIR}/${SVC}-${ARCH}.tar.gz.part-"* &>/dev/null; then
      PARTS=$(ls "${IMAGE_DIR}/${SVC}-${ARCH}.tar.gz.part-"* | wc -l | tr -d ' ')
      echo "  Reassembling ${SVC} (${PARTS} chunks) ..."
      cat "${IMAGE_DIR}/${SVC}-${ARCH}.tar.gz.part-"* > "$TARBALL"
    fi

    if [ ! -f "$TARBALL" ]; then
      echo "  WARNING: $TARBALL not found, skipping."
      continue
    fi

    SIZE=$(du -h "$TARBALL" | cut -f1)
    echo "  Loading ${SVC} ($SIZE) ..."
    gunzip -c "$TARBALL" | docker load

    # Clean up reassembled tarball to free disk space
    if ls "${IMAGE_DIR}/${SVC}-${ARCH}.tar.gz.part-"* &>/dev/null; then
      rm -f "$TARBALL"
    fi
    echo ""
  done

  echo "Loaded images:"
  docker images "fortiai-demo/*" --format "table {{.Repository}}\t{{.Tag}}\t{{.Size}}\t{{.ID}}"
  echo ""
}

# ── Start the stack ───────────────────────────────────────────────────────────
start_stack() {
  echo ""
  echo "═══════════════════════════════════════════════════════════════"
  echo "  Starting FortiAI Galaxy Store"
  echo "═══════════════════════════════════════════════════════════════"
  echo ""

  cd "$SCRIPT_DIR"
  docker compose up -d

  echo ""
  echo "Waiting for services to come up (up to 60s) ..."
  TRIES=0
  MAX_TRIES=30
  while [ $TRIES -lt $MAX_TRIES ]; do
    if curl -sf http://localhost:8000/healthz &>/dev/null; then
      echo "  API is healthy."
      break
    fi
    TRIES=$((TRIES + 1))
    sleep 2
  done

  if [ $TRIES -ge $MAX_TRIES ]; then
    echo "  WARNING: API healthcheck timed out. Check logs with: ./deploy.sh --logs"
  fi

  echo ""
  docker compose ps
  echo ""

  # Grab the host IP for display
  HOST_IP=$(hostname -I 2>/dev/null | awk '{print $1}' || echo "localhost")
  API_PORT=$(grep -E '^API_PORT=' "$SCRIPT_DIR/.env" 2>/dev/null | cut -d= -f2 || echo "8000")
  FE_PORT=$(grep -E '^FRONTEND_PORT=' "$SCRIPT_DIR/.env" 2>/dev/null | cut -d= -f2 || echo "3000")

  echo "═══════════════════════════════════════════════════════════════"
  echo "  FortiAI Galaxy Store is running!"
  echo ""
  echo "  Frontend:  http://${HOST_IP}:${FE_PORT}"
  echo "  API:       http://${HOST_IP}:${API_PORT}"
  echo "  Health:    http://${HOST_IP}:${API_PORT}/healthz"
  echo ""
  echo "  Admin:     admin@ftnt-apac-demo.local / (see .env ADMIN_PASSWORD)"
  echo "═══════════════════════════════════════════════════════════════"
}

# ── Tear down ─────────────────────────────────────────────────────────────────
tear_down() {
  echo "Stopping FortiAI Galaxy Store ..."
  cd "$SCRIPT_DIR"
  docker compose down
  echo "Done."
}

# ── Status / logs ─────────────────────────────────────────────────────────────
show_status() {
  cd "$SCRIPT_DIR"
  docker compose ps
}

show_logs() {
  cd "$SCRIPT_DIR"
  docker compose logs -f --tail=50
}

# ── Main ──────────────────────────────────────────────────────────────────────
check_docker

case "$ACTION" in
  full)   load_images; ensure_env; start_stack ;;
  load)   load_images ;;
  up)     ensure_env; start_stack ;;
  down)   tear_down ;;
  status) show_status ;;
  logs)   show_logs ;;
esac
